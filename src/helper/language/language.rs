//! Localization and translation management via gettext.
//!
//! The module wraps the `gettext-rs` bindings and automates the search for translation
//! files (`.mo`). It supports the different installation layouts (distribution packages,
//! Flatpak, Snap, AppImage, local development) and gives thread-safe access to the
//! current settings.
//!
//! # Two text domains
//!
//! * The **application domain** is the one you pass to [`init_language`]. Its catalogs come
//!   with your application.
//! * The **library domain** [`LIB_DOMAIN`] holds the texts of this library (button labels,
//!   dialog titles, …). Its catalogs are compiled into the library, so they work in every
//!   package format without installing anything. A copy installed in the locale directory
//!   (`<locale dir>/<lang>/LC_MESSAGES/atlbase.mo`) is preferred, which lets a
//!   distribution ship corrected translations.
//!
//! [`translate`] (and the [`gettext!`](crate::gettext!) macro) look in the application
//! domain first and in the library domain second, so an application can override every
//! text of the library by translating the same `msgid`.
//!
//! # Where the translations of the application are searched
//!
//! The first directory in this list that contains a catalog of the application domain
//! (`<dir>/<lang>/LC_MESSAGES/<domain>.mo`) wins:
//!
//! 1. the directory in the environment variable `ATL_LOCALEDIR` (used as it is, if it
//!    exists — for testing),
//! 2. inside a **Snap**: `default_dir`, `/usr/share/locale` and `share/locale` below `$SNAP`,
//! 3. inside an **AppImage**: `default_dir` and `usr/share/locale` below `$APPDIR`,
//! 4. the `default_dir` that was passed to [`init_language`],
//! 5. inside a **Flatpak**: `/app/share/locale`,
//! 6. `/usr/share/locale`,
//! 7. `locale` below every directory of `$XDG_DATA_DIRS`.
//!
//! If no directory contains a catalog, `default_dir` is used.
//!
//! # Examples
//!
//! ```no_run
//! use atlbase::{gettext, prelude::init_language};
//!
//! // "demo" is the name of your .mo files, "/usr/share/locale" where they are installed
//! init_language("demo", "/usr/share/locale", false);
//! println!("{}", gettext!("Welcome"));
//! ```

use gettextrs::{
    LocaleCategory, bind_textdomain_codeset, bindtextdomain, dgettext, setlocale, textdomain,
};
use std::env;
use std::ffi::OsString;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::{LazyLock, Mutex, MutexGuard};

/// The text domain of this library.
///
/// It is the name of the crate and the name of the `.mo` files compiled from `po/`.
/// Pass it to [`init_language`] if you only want the translations of the library.
pub const LIB_DOMAIN: &str = env!("CARGO_PKG_NAME");

// `EMBEDDED_CATALOGS`: the compiled catalogs of the library, generated by build.rs
include!(concat!(env!("OUT_DIR"), "/embedded_catalogs.rs"));

/// The current locale directory.
static CURRENT_LOCALEDIR: LazyLock<Mutex<PathBuf>> = LazyLock::new(|| Mutex::new(PathBuf::new()));

/// The current text domain (usually the name of the application).
static CURRENT_DOMAIN: Mutex<String> = Mutex::new(String::new());

/// Locks a mutex; a panic in another thread must not disable the translations.
fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}

/// Sets the directory that contains the translation files.
///
/// The path is only applied if it exists and is a directory. [`init_language`] does this
/// for you; call it afterwards only to override the choice.
///
/// # Arguments
///
/// * `dir` - The locale directory, for example `/usr/share/locale`.
pub fn set_language_dir(dir: &str) {
    let path = Path::new(dir);
    if path.is_dir() {
        *lock(&CURRENT_LOCALEDIR) = path.to_path_buf();
    }
}

/// Returns a copy of the current locale directory.
///
/// The path is empty as long as neither [`set_language_dir`] nor [`init_language`] found a
/// directory.
pub fn get_language_dir() -> PathBuf {
    lock(&CURRENT_LOCALEDIR).clone()
}

/// Returns the current text domain.
///
/// The text is empty until [`init_language`] has been called.
pub fn get_current_domain() -> String {
    lock(&CURRENT_DOMAIN).clone()
}

/// Translates a text.
///
/// The text is searched in the application domain (see [`get_current_domain`]) first and in
/// the library domain [`LIB_DOMAIN`] second. If there is no translation, the original text is
/// returned. An empty text stays empty (gettext would return the header of the catalog).
///
/// Prefer the [`gettext!`](crate::gettext!) macro in application code.
///
/// # Examples
///
/// ```
/// use atlbase::helper::language::language::translate;
///
/// // nothing is translated before `init_language` was called
/// assert_eq!(translate("Hello"), "Hello");
/// assert_eq!(translate(""), "");
/// ```
pub fn translate(msgid: impl AsRef<str>) -> String {
    let msgid = msgid.as_ref();
    // gettext cannot handle empty strings (header) or interior NUL bytes (C string)
    if msgid.is_empty() || msgid.contains('\0') {
        return msgid.to_string();
    }

    let domain = get_current_domain();
    if !domain.is_empty() && domain != LIB_DOMAIN {
        let text = dgettext(domain, msgid);
        if text != msgid {
            return text;
        }
    }
    dgettext(LIB_DOMAIN, msgid)
}

/// Looks up an environment variable; empty values count as unset.
type EnvLookup<'a> = &'a dyn Fn(&str) -> Option<OsString>;

/// Moves an absolute path below `root` (`/usr/share/locale` → `<root>/usr/share/locale`).
fn rebase(root: &Path, dir: &Path) -> PathBuf {
    root.join(dir.strip_prefix("/").unwrap_or(dir))
}

/// All directories that may hold translations, in search order (see the module docs).
fn locale_dir_candidates(default_dir: &str, var: EnvLookup) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = Vec::new();
    let mut push = |dir: PathBuf| {
        if !dirs.contains(&dir) {
            dirs.push(dir);
        }
    };
    let default_path = Path::new(default_dir);

    // Snap and AppImage mount the program below a root that is only known at run time;
    // an absolute default_dir such as /usr/share/locale lives below that root there
    for root_var in ["SNAP", "APPDIR"] {
        if let Some(root) = var(root_var).map(PathBuf::from) {
            if !default_dir.is_empty() {
                push(rebase(&root, default_path));
            }
            push(root.join("usr/share/locale"));
            push(root.join("share/locale"));
        }
    }

    if !default_dir.is_empty() {
        push(default_path.to_path_buf());
    }
    if var("FLATPAK_ID").is_some() {
        push(PathBuf::from("/app/share/locale"));
    }
    push(PathBuf::from("/usr/share/locale"));

    let data_dirs = var("XDG_DATA_DIRS")
        .map(|list| env::split_paths(&list).collect::<Vec<_>>())
        .unwrap_or_else(|| {
            vec![
                PathBuf::from("/usr/local/share"),
                PathBuf::from("/usr/share"),
            ]
        });
    for data_dir in data_dirs.into_iter().filter(|dir| dir.is_absolute()) {
        push(data_dir.join("locale"));
    }

    dirs
}

/// Checks whether `dir` holds a catalog for `domain` in at least one language.
fn has_catalog(dir: &Path, domain: &str) -> bool {
    let Ok(entries) = fs::read_dir(dir) else {
        return false;
    };
    entries.flatten().any(|lang| {
        lang.path()
            .join("LC_MESSAGES")
            .join(format!("{domain}.mo"))
            .is_file()
    })
}

/// Chooses the locale directory for `domain` (see the module docs for the order).
fn select_locale_dir(default_dir: &str, domain: &str, var: EnvLookup) -> Option<PathBuf> {
    if let Some(dir) = var("ATL_LOCALEDIR").map(PathBuf::from)
        && dir.is_dir()
    {
        return Some(dir);
    }

    locale_dir_candidates(default_dir, var)
        .into_iter()
        .find(|dir| has_catalog(dir, domain))
        .or_else(|| Some(PathBuf::from(default_dir)).filter(|dir| dir.is_dir()))
}

/// Writes the catalogs that are compiled into the library to the cache directory of the
/// user and returns the locale directory that contains them.
///
/// The directory is `<cache dir>/atlbase/locale-<version>`. Flatpak and Snap point the
/// cache directory into the private data of the application, so this works in every
/// sandbox. Existing identical files are not rewritten, and files are replaced atomically,
/// so several running instances cannot corrupt each other.
fn install_embedded_catalogs() -> Option<PathBuf> {
    if EMBEDDED_CATALOGS.is_empty() {
        return None;
    }

    let cache = directories::ProjectDirs::from("", "", LIB_DOMAIN)?;
    let root = cache
        .cache_dir()
        .join(format!("locale-{}", env!("CARGO_PKG_VERSION")));

    for (lang, bytes) in EMBEDDED_CATALOGS {
        let dir = root.join(lang).join("LC_MESSAGES");
        let file = dir.join(format!("{LIB_DOMAIN}.mo"));
        if fs::read(&file).is_ok_and(|current| current == *bytes) {
            continue;
        }

        fs::create_dir_all(&dir).ok()?;
        let temp = dir.join(format!("{LIB_DOMAIN}.mo.{}", std::process::id()));
        fs::write(&temp, bytes).ok()?;
        fs::rename(&temp, &file).ok()?;
    }
    Some(root)
}

/// Binds `domain` to `dir` and sets the codeset to UTF-8.
fn bind_domain(domain: &str, dir: &Path) {
    if let Err(e) = bindtextdomain(domain, dir) {
        eprintln!("[WARN] Failed to bind textdomain '{}': {}", domain, e);
    }
    if let Err(e) = bind_textdomain_codeset(domain, "UTF-8") {
        eprintln!("[WARN] Failed to set the codeset of '{}': {}", domain, e);
    }
}

/// Binds the text domain of the library: installed catalogs first, embedded ones second.
fn bind_library_domain(default_dir: &str, var: EnvLookup) {
    let dir = select_locale_dir(default_dir, LIB_DOMAIN, var)
        .filter(|dir| has_catalog(dir, LIB_DOMAIN))
        .or_else(install_embedded_catalogs);

    if let Some(dir) = dir {
        bind_domain(LIB_DOMAIN, &dir);
    }
}

/// Initializes gettext and binds the translations of the application and the library.
///
/// Call it once at program start, before the first window is created. It
///
/// 1. stores `domain` as the current text domain,
/// 2. sets the locale from the environment (`LC_ALL`, `LC_MESSAGES`, `LANG`),
/// 3. binds the library domain [`LIB_DOMAIN`],
/// 4. searches the locale directory of the application (see the [module
///    documentation](self) for the order) and binds `domain` to it, and
/// 5. makes `domain` the default domain.
///
/// Problems are printed to `stderr`; the function never panics. Without translation files
/// all texts simply stay in English.
///
/// # Arguments
///
/// * `domain` - The text domain of the application, usually its name (`"atlantis-shell"`).
///   The catalogs are called `<domain>.mo`.
/// * `default_dir` - The directory with the catalogs of your application, for example the
///   `LOCALEDIR` that your build system installs to (`/usr/share/locale`, in a Flatpak
///   `/app/share/locale`). Use `env!("COMPILED_LOCALE_DIR")` during development.
/// * `debug_lang` - If `true`, the language is forced to `en_US.UTF-8`. Only for debugging.
///
/// # Safety notes
///
/// With `debug_lang` the function changes the environment variables `LC_ALL` and `LANG`.
/// Changing the environment is not thread-safe, so call it before other threads start.
///
/// # Examples
///
/// ```no_run
/// use atlbase::{gettext, prelude::init_language};
///
/// init_language("demo", "/usr/share/locale", false);
/// println!("{}", gettext!("Welcome"));
/// ```
pub fn init_language(domain: &str, default_dir: &str, debug_lang: bool) {
    *lock(&CURRENT_DOMAIN) = domain.to_string();

    if debug_lang {
        // SAFETY: documented above; the caller must not have other threads running yet.
        unsafe {
            env::set_var("LC_ALL", "en_US.UTF-8");
            env::set_var("LANG", "en_US.UTF-8");
        }
        setlocale(LocaleCategory::LcAll, "en_US.UTF-8");
    } else {
        setlocale(LocaleCategory::LcAll, "");
    }

    let var = |key: &str| env::var_os(key).filter(|value| !value.is_empty());

    bind_library_domain(default_dir, &var);

    if let Some(dir) = select_locale_dir(default_dir, domain, &var) {
        set_language_dir(&dir.to_string_lossy());
    }

    let mut dir = get_language_dir();
    if dir.as_os_str().is_empty() {
        dir = PathBuf::from(default_dir);
    }

    bind_domain(domain, &dir);
    if let Err(e) = textdomain(domain) {
        eprintln!("[WARN] Failed to set textdomain '{}': {}", domain, e);
    }

    println!(
        "[INFO] Locale init: domain='{}', dir='{}'",
        domain,
        dir.display()
    );
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    /// An environment from a list of variables, independent of the real one.
    fn env_of(vars: &[(&str, &str)]) -> impl Fn(&str) -> Option<OsString> + use<> {
        let map: HashMap<String, OsString> = vars
            .iter()
            .map(|(key, value)| (key.to_string(), OsString::from(value)))
            .collect();
        move |key| map.get(key).cloned()
    }

    fn catalog(root: &Path, lang: &str, domain: &str) {
        let dir = root.join(lang).join("LC_MESSAGES");
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join(format!("{domain}.mo")), b"").unwrap();
    }

    #[test]
    fn candidates_cover_every_package_format() {
        let plain = locale_dir_candidates("/opt/app/locale", &env_of(&[]));
        assert_eq!(plain[0], Path::new("/opt/app/locale"));
        assert!(plain.contains(&PathBuf::from("/usr/share/locale")));
        assert!(plain.contains(&PathBuf::from("/usr/local/share/locale")));

        let snap = locale_dir_candidates("/usr/share/locale", &env_of(&[("SNAP", "/snap/app/7")]));
        assert_eq!(snap[0], Path::new("/snap/app/7/usr/share/locale"));
        assert!(snap.contains(&PathBuf::from("/snap/app/7/share/locale")));

        let appimage =
            locale_dir_candidates("/usr/share/locale", &env_of(&[("APPDIR", "/tmp/.mount_x")]));
        assert_eq!(appimage[0], Path::new("/tmp/.mount_x/usr/share/locale"));

        let flatpak = locale_dir_candidates(
            "/app/share/locale",
            &env_of(&[("FLATPAK_ID", "org.example.App")]),
        );
        assert_eq!(flatpak[0], Path::new("/app/share/locale"));

        let xdg = locale_dir_candidates("", &env_of(&[("XDG_DATA_DIRS", "/a:/b:relative")]));
        assert!(
            xdg.contains(&PathBuf::from("/a/locale")) && xdg.contains(&PathBuf::from("/b/locale"))
        );
        assert!(!xdg.iter().any(|dir| dir.starts_with("relative")));
        assert!(!xdg.contains(&PathBuf::from("/usr/local/share/locale")));
    }

    #[test]
    fn first_directory_with_a_catalog_wins() {
        let root = tempfile::tempdir().unwrap();
        let empty = root.path().join("empty");
        let with_catalog = root.path().join("with");
        fs::create_dir_all(&empty).unwrap();
        catalog(&with_catalog, "de", "demo");

        let snap = root.path().join("snap");
        catalog(&snap.join("usr/share/locale"), "de", "demo");

        // inside a Snap the catalog below $SNAP is found although default_dir exists too
        let var = env_of(&[("SNAP", snap.to_str().unwrap())]);
        let default_dir = with_catalog.to_str().unwrap();
        assert_eq!(
            select_locale_dir(default_dir, "demo", &var),
            Some(snap.join("usr/share/locale"))
        );

        // otherwise default_dir is used
        assert_eq!(
            select_locale_dir(default_dir, "demo", &env_of(&[])),
            Some(with_catalog.clone())
        );

        // no catalog anywhere: the (existing) default_dir is the fallback
        let fallback = select_locale_dir(empty.to_str().unwrap(), "unknown-domain", &env_of(&[]));
        assert_eq!(fallback, Some(empty.clone()));

        // an explicit ATL_LOCALEDIR beats everything, if it exists
        let var = env_of(&[("ATL_LOCALEDIR", empty.to_str().unwrap())]);
        assert_eq!(select_locale_dir(default_dir, "demo", &var), Some(empty));
        let var = env_of(&[("ATL_LOCALEDIR", "/does/not/exist")]);
        assert_eq!(
            select_locale_dir(default_dir, "demo", &var),
            Some(with_catalog)
        );
    }

    #[test]
    fn translate_keeps_untranslated_text() {
        assert_eq!(translate("not in any catalog"), "not in any catalog");
        assert_eq!(translate(""), "");
        assert_eq!(translate("nul\0byte"), "nul\0byte");
    }
}
